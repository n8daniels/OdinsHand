<#
  Creates or refreshes an isolated dedicated-server profile for the project in odinshand.json, next to your dedicated server install.
  It never touches your repository or the game folder, and the harness plugin is NOT put on the server (the server runs what ships).

      <server root>\<name>ServerProfile\BepInEx    BepInEx 5 core [+ Jotunn] + the DLLs listed in server.plugins + server.configFiles

  One-time setup: install the dedicated server with steamcmd (app 896660) so that  <server root>\server\valheim_server.exe  exists:
      steamcmd +force_install_dir <server root>\server +login anonymous +app_update 896660 validate +quit

  odinshand.json (all keys optional except where noted):
      "server": {
        "root":        "D:\\ValheimDedicated",     // or set the VALHEIM_SERVER_ROOT environment variable
        "name":        "MyMod-Test",               // server name (default "<name>-Test")
        "world":       "MyModServer",              // default "<name>Server"
        "port":        2456,
        "password":    "harnesspw1",               // at least 5 characters, and not contained in the server name
        "plugins":     [ "src/MyMod/bin/Release/MyMod.dll" ],     // mod DLLs for the SERVER (relative to the project)
        "configFiles": { "com.me.mymod.cfg": "dev/server-config/com.me.mymod.cfg" }   // server config that deliberately differs from the client's
      }

  Usage:  .\scripts\New-ServerProfile.ps1 [-Project <dir>] [-CoreSource <BepInEx\core>]
#>
param([string]$Project = "", [string]$CoreSource = "")
$ErrorActionPreference = "Stop"
. "$PSScriptRoot\_Config.ps1"
$p = Get-OdinsConfig $Project
$s = Get-OdinsServerConfig $p

if (-not (Test-Path $s.Exe)) {
  throw "No dedicated server at '$($s.Exe)'. Install it with steamcmd (app 896660) into '$($s.Root)\server', or set server.root / VALHEIM_SERVER_ROOT. See the comment at the top of this script."
}
if (-not $CoreSource) { $CoreSource = Get-BepInExCore }
if (-not (Test-Path "$CoreSource\BepInEx.Preloader.dll")) { throw "No BepInEx core at '$CoreSource' (pass -CoreSource)." }

$bep = Join-Path $s.ProfileDir "BepInEx"
New-Item -ItemType Directory -Force "$bep\core", "$bep\plugins\$($p.Name)", "$bep\config" | Out-Null
Copy-Item "$CoreSource\*" "$bep\core" -Force

if ($p.Cfg.jotunn) {
  $jot = "$env:USERPROFILE\.nuget\packages\jotunnlib\$($p.Cfg.jotunn)\lib\net462\Jotunn.dll"
  if (-not (Test-Path $jot)) { throw "JotunnLib $($p.Cfg.jotunn) is not in the NuGet cache. Run 'dotnet restore' on the solution first." }
  New-Item -ItemType Directory -Force "$bep\plugins\Jotunn" | Out-Null
  Copy-Item $jot "$bep\plugins\Jotunn\Jotunn.dll" -Force
}

foreach ($rel in $s.Plugins) {
  $src = Join-Path $p.Root $rel
  if (-not (Test-Path $src)) { throw "Server plugin not built: $src. Build the project first." }
  Copy-Item $src "$bep\plugins\$($p.Name)" -Force
}
foreach ($name in $s.ConfigFiles.Keys) {
  $src = Join-Path $p.Root $s.ConfigFiles[$name]
  if (-not (Test-Path $src)) { throw "Server config file not found: $src" }
  Copy-Item $src "$bep\config\$name" -Force
}

# Valheim refuses a password shorter than 5 characters or one that appears inside the server name.
if ($s.Password.Length -lt 5) { throw "server.password must be at least 5 characters." }
if ($s.Name.ToLower().Contains($s.Password.ToLower())) { throw "server.password must not appear inside server.name." }

$launcher = @"
# Starts the Valheim dedicated server for $($p.Name) (BepInEx + the mod only; no harness). Generated by Odin's Hand; safe to regenerate.
`$ErrorActionPreference = 'Stop'
`$server    = '$($s.Root)\server'
`$profile   = '$($s.ProfileDir)'
`$preloader = Join-Path `$profile 'BepInEx\core\BepInEx.Preloader.dll'
`$exe       = Join-Path `$server 'valheim_server.exe'
foreach (`$f in @(`$exe, `$preloader)) { if (-not (Test-Path `$f)) { throw "Missing: `$f" } }
foreach (`$old in @((Join-Path `$profile 'BepInEx\LogOutput.log'), (Join-Path `$profile 'server.log'))) { if (Test-Path `$old) { Remove-Item `$old -Force } }
`$env:SteamAppId = '892970'
`$arguments = @(
  '-nographics', '-batchmode',
  '-name', '$($s.Name)', '-port', '$($s.Port)', '-world', '$($s.World)', '-password', '$($s.Password)', '-public', '0',
  '-logFile', "``"`$(Join-Path `$profile 'server.log')``"",
  '--doorstop-enabled', 'true', '--doorstop-target-assembly', "``"`$preloader``""
) -join ' '
Start-Process -FilePath `$exe -WorkingDirectory `$server -ArgumentList `$arguments
Write-Host "Server starting. Logs: `$profile\server.log and `$profile\BepInEx\LogOutput.log"
"@
Set-Content -Path (Join-Path $s.ProfileDir "Start-$($p.Name)Server.ps1") -Value $launcher -Encoding UTF8
Write-Host "Server profile ready: $($s.ProfileDir)" -ForegroundColor Green
